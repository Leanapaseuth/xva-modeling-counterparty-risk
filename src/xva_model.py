# CVA

# valeurs par défaut pour le taux de recouvrement de la contrepartie et chance de défaut de la contrepartie par an, peuvent être changées lorsqu'on appelle la fonction
def compute_cva(times, dates, expected_exposure, base_discount_curve, end_date=None, recovery_rate=0.40, default_intensity=0.02):
  LGD = 1 - recovery_rate # perte en cas de défaut de la contrepartie
  cva = 0.0
  for j in range(1, len(times)):
    if dates[j] > end_date: # évite les calculs inutiles sur la période après maturité des contrats (où l'EE est nulle)
      break
    # Probabilité que le défaut arrive entre t_j-1 et t_j
    prob_default = (np.exp(-default_intensity * times[j-1]) - np.exp(-default_intensity * times[j]))

    # Exposition moyenne sur la période (on prend le max avec 0 car risque unilatéral)
    avg_exposure = 0.5 * (expected_exposure[j] + expected_exposure[j-1])

    df = base_discount_curve.discount(dates[j])
    cva += LGD * prob_default * avg_exposure * df
  return cva

# DVA

# Paramètres pour notre propre banque par défaut (modifiables lorsqu'on appelle la fonction)
def compute_dva(times, dates, expected_exposure_neg, base_discount_curve, end_date=None, own_recovery_rate=0.40, own_default_intensity=0.01):
  own_LGD = 1 - own_recovery_rate
  dva = 0.0
  for j in range(1, len(times)):
    if dates[j] > end_date:
      break
    # Probabilité que notre banque fasse défaut entre t_j-1 et t_j
    prob_own_default = (np.exp(-own_default_intensity * times[j-1]) - np.exp(-own_default_intensity * times[j]))

    # Exposition négative moyenne (combien l'on devrait au client si l'on faisait défaut)
    # On prend max(0, -NPV) car c'est une perte pour le client, donc un "gain" DVA pour nous
    avg_neg_exposure = 0.5 * (expected_exposure_neg[j] + expected_exposure_neg[j-1])

    df = base_discount_curve.discount(dates[j])
    dva += own_LGD * prob_own_default * avg_neg_exposure * df
  return dva

# FVA (hypothèse portefeuille non collatéralisé, donc pas de calcul du MVA)

# 100 bps, spread de financement de notre banque par défaut
def compute_fva(times, dates, expected_exposure, base_discount_curve, end_date=None, funding_spread=0.01):
  fva = 0.0
  for j in range(1, len(times)):
    if dates[j] > end_date:
      break
    dt = times[j] - times[j-1]
    df = base_discount_curve.discount(dates[j])
    avg_exposure = 0.5 * (expected_exposure[j] + expected_exposure[j-1])
    fva += funding_spread * avg_exposure * df * dt
  return fva

# KVA

# RW pondération réglementaire (risk weight), CR ratio de capital réglementaire (exigence minimale de Bâle III) et coût du capital (rendement exigé par les actionnaires autour de 8–12%) par défaut
def compute_kva(times, dates, expected_exposure, base_discount_curve, end_date=None, RW=1.0, CR=0.08, cost_of_capital=0.10):
  kva = 0.0
  for j in range(1, len(times)):
    if dates[j] > end_date:
      break
    dt = times[j] - times[j-1]
    df = base_discount_curve.discount(dates[j])
    avg_exposure = 0.5 * (expected_exposure[j] + expected_exposure[j-1])
    capital_t = RW * CR * avg_exposure # capital réglementaire requis
    kva += cost_of_capital * capital_t * df * dt
  return kva

