def pick_latest_before(series, target):
  series = [(d, v) for d, v in series if d <= target]
  if not series:
    raise ValueError("Aucune donnée avant la date cible.")
  return max(series, key=lambda x: x[0])

def fetch_estr_rate(target):
  url = "https://api.estr.dev/historical"
  data = requests.get(url, timeout=30).json()
  series = [(dt.date.fromisoformat(x["date"]), float(x["value"]) / 100.0) for x in data]
  return pick_latest_before(series, target)

def fetch_euribor_6m_series():
  url = "https://euriborrates.com/en/term-comparison/euribor-6m"
  html = requests.get(url, timeout=30).text
  dfs = pd.read_html(StringIO(html))
  for df in dfs:
    if "Date" in df.columns and "Rate (%)" in df.columns:
      series = []
      for _, row in df.iterrows():
        d = pd.to_datetime(row["Date"], errors="coerce").date()
        v = float(str(row["Rate (%)"]).replace("%", "").strip()) / 100.0
        series.append((d, v))
      return series

