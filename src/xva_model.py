def build_irs_payer(notional, start_date, maturity_date, fixed_rate, index_6m, discount_handle, daycount, calendar):
  schedule = ql.Schedule(
    start_date, maturity_date, ql.Period(ql.Semiannual), calendar, # construit l’échéancier semestriel de paiements de today à maturity
    ql.ModifiedFollowing, ql.ModifiedFollowing, ql.DateGeneration.Forward, False # garantit que toutes les périodes font bien 6 mois, sauf éventuellement la dernière si la date de fin est irrégulière
  )
  # Création du swap (jambe fixe puis jambe flottante)
  swap = ql.VanillaSwap(
    ql.VanillaSwap.Payer, # payeur du taux fixe. En échange, on reçoit le taux flottant (l'Euribor)
    notional,             # Le capital de référence sur lequel sont calculés les intérêts. Ce montant n'est jamais échangé, il sert juste de base de calcul
    schedule,             # Le calendrier que nous avons défini précédemment (tous les 6 mois)
    fixed_rate,           # Le taux fixe que l'on s'engage à payer quoi qu'il arrive
    daycount,             # convention de calcul qui stipule que l'intérêt annuel est divisé par 360 jours
    schedule,             # même calendrier pour la jambe flottante
    index_6m,             # capteur qui va lire le taux Euribor sur le marché (c'est cet élément qui rend la valeur du swap incertaine dans le futur)
    0.0,                  # spread, marge supplémentaire (ici 0) que l'on pourrait ajouter au taux flottant
    daycount              # même convention de calcul pour les flux variables
  )

  # attacher le moteur de pricing
  engine = ql.DiscountingSwapEngine(discount_handle) # crée une calculatrice capable d'évaluer la valeur d'un Swap en utilisant la méthode de l'actualisation des flux de trésorerie et en utilisant la courbe €STR
  swap.setPricingEngine(engine) # le swap n'est plus une simple liste de dates et de taux, il devient un instrument financier

  return swap

def build_irs_receiver(notional, start_date, maturity_date, fixed_rate, index_6m, discount_handle, daycount, calendar):
  schedule = ql.Schedule(
    start_date, maturity_date, ql.Period(ql.Semiannual), calendar,
    ql.ModifiedFollowing, ql.ModifiedFollowing, ql.DateGeneration.Forward, False
  )
  swap = ql.VanillaSwap(
    ql.VanillaSwap.Receiver, # on reçoit la jambe fixe et on paie la jambe flottante
    notional,
    schedule,
    fixed_rate,
    daycount,
    schedule,
    index_6m,
    0.0,
    daycount
  )
  engine = ql.DiscountingSwapEngine(discount_handle)
  swap.setPricingEngine(engine)
  return swap

def build_zero_coupon_bond(notional, start_date, maturity_date, discount_handle, calendar):
  bond = ql.ZeroCouponBond(
    2, # settlementDays
    calendar,
    notional,
    maturity_date,
    ql.ModifiedFollowing,
    100.0, # redemption (100% remboursement à maturité)
    start_date
  )
  engine = ql.DiscountingBondEngine(discount_handle)
  bond.setPricingEngine(engine)
  return bond

def build_fra_6x12(notional, today, fixed_rate, index_6m, discount_handle, calendar):
  # dates FRA : start = today + 6M, end = today + 12M
  start_date = calendar.advance(today, ql.Period(6, ql.Months))
  end_date = calendar.advance(today, ql.Period(12, ql.Months))

  fra = ql.ForwardRateAgreement(
    index_6m,
    start_date,
    end_date,
    ql.Position.Long, # long = on gagne si le taux réalisé euribor > taux fixe
    fixed_rate,
    notional,
    discount_handle,
  )
  return fra, start_date # ForwardRateAgreement n’expose pas la date de cash-settlement donc il faut la sortir manuellement pour l'utiliser ensuite dans le MC

def build_cap(notional, start_date, maturity_date, strike, index_6m, daycount, calendar, discount_handle, cap_vol=0.01): # long du cap par défaut (paie si l’Euribor 6M dépasse un strike à chaque période 6M)
  schedule = ql.Schedule(
    start_date, maturity_date, ql.Period(ql.Semiannual), calendar,
    ql.ModifiedFollowing, ql.ModifiedFollowing, ql.DateGeneration.Forward, False
  )

  # floating leg pour construire le cap
  floating_leg = ql.IborLeg([notional], schedule, index_6m, daycount)
  cap = ql.Cap(floating_leg, [strike])

  vol_handle = ql.QuoteHandle(ql.SimpleQuote(cap_vol)) # Black vol (constante)
  engine = ql.BachelierCapFloorEngine(discount_handle, vol_handle) # modèle Normal/Bachelier
  cap.setPricingEngine(engine)

  return cap

def build_swaption_5y_into_5y(notional, start_date, fixed_rate, index_6m, daycount, calendar, discount_handle, vol=0.01, payer=True): # option qui nous donne dans 5 ans, le droit d’entrer dans un swap de 5 ans
  # exercice dans 5 ans
  exercise_date = calendar.advance(start_date, ql.Period(5, ql.Years))
  # swap sous-jacent 5Y
  maturity_date = calendar.advance(exercise_date, ql.Period(5, ql.Years))

  schedule = ql.Schedule(
    exercise_date, maturity_date, ql.Period(ql.Semiannual), calendar,
    ql.ModifiedFollowing, ql.ModifiedFollowing, ql.DateGeneration.Forward, False
  )

  swap_type = ql.VanillaSwap.Payer if payer else ql.VanillaSwap.Receiver

  underlying = ql.VanillaSwap(
    swap_type,
    notional,
    schedule,
    fixed_rate,
    daycount,
    schedule,
    index_6m,
    0.0,
    daycount
  )

  exercise = ql.EuropeanExercise(exercise_date)
  swaption = ql.Swaption(underlying, exercise)

  vol_handle = ql.QuoteHandle(ql.SimpleQuote(vol))
  engine = ql.BachelierSwaptionEngine(discount_handle, vol_handle)
  swaption.setPricingEngine(engine)

  return swaption, exercise_date

