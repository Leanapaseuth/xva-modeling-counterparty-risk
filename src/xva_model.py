  prev_t = 0.0 # temps précédent pour calculer dt

  for j, t in enumerate(times): # j = 0, 1, 2, …, 119 et t = times[j]
    dt = t - prev_t # pas de temps entre deux dates successives
    prev_t = t # met à jour le temps précédent

    z1 = rng.standard_normal() # tirage normal standard pour €STR
    z2 = rho * z1 + np.sqrt(1 - rho**2) * rng.standard_normal() # tire un choc corrélé pour Euribor

    sig_str = sigma_piecewise(t, sigma_str_times, sigma_str_vals) # volatilité €STR pour cet horizon
    sig_fwd = sigma_piecewise(t, sigma_fwd_times, sigma_fwd_vals) # volatilité Euribor pour cet horizon

    # Euler Hull-White: dr = a*(theta - r)*dt + sigma*sqrt(dt)*z
    # approximation theta (taux initiaux)
    theta_str = str_flat_rate
    theta_fwd = euribor_flat_rate

    r_str = r_str + a_str * (theta_str - r_str) * dt + sig_str * np.sqrt(dt) * z1 # mise à jour Euler du taux court €STR
    r_fwd = r_fwd + a_fwd * (theta_fwd - r_fwd) * dt + sig_fwd * np.sqrt(dt) * z2 # mise à jour Euler du taux court Euribor

    eval_date = dates[j]
    ql.Settings.instance().evaluationDate = eval_date

